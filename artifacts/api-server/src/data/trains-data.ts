export interface TrainRecord {
  trainNumber: string;
  trainName: string;
  fromStation: string;
  toStation: string;
  trainType: string;
  routeKey: string;
  departureTime: string;
  arrivalTime: string;
  durationMins: number;
}

function t(
  num: string, name: string, from: string, to: string,
  type: string, routeKey: string, dep = "--:--", arr = "--:--", dur = 0
): TrainRecord {
  return { trainNumber: num, trainName: name, fromStation: from, toStation: to, trainType: type, routeKey, departureTime: dep, arrivalTime: arr, durationMins: dur };
}

function pair(
  a: string, b: string,
  nameA: string, nameB: string,
  from: string, to: string,
  type: string, routeKey: string,
  dep = "--:--", arr = "--:--", dur = 0
): TrainRecord[] {
  return [
    t(a, nameA, from, to, type, routeKey, dep, arr, dur),
    t(b, nameB, to, from, type, reverseKey(routeKey), arr, dep, dur),
  ];
}

function reverseKey(key: string): string {
  const parts = key.split("-");
  if (parts.length === 2) return `${parts[1]}-${parts[0]}`;
  return key;
}

function exp(
  a: string, b: string, name: string, from: string, to: string, routeKey: string
): TrainRecord[] {
  return pair(a, b, name, name, from, to, "Express", routeKey);
}

