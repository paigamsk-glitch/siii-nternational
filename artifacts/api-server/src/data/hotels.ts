export function searchHotels(params: {
  destination?: string;
  minPrice?: number;
  maxPrice?: number;
  rating?: number;
  country?: string;
}) {
  let results = [...hotelsData];

  if (params.destination) {
    const dest = params.destination.toLowerCase();
    results = results.filter(
      (h) =>
        h.destination.toLowerCase().includes(dest) ||
        h.country.toLowerCase().includes(dest) ||
        h.name.toLowerCase().includes(dest)
    );
  }
  if (params.country) {
    const country = params.country.toLowerCase();
    results = results.filter((h) => h.country.toLowerCase().includes(country));
  }
  if (params.minPrice) {
    results = results.filter((h) => h.pricePerNight >= params.minPrice!);
  }
  if (params.maxPrice) {
    results = results.filter((h) => h.pricePerNight <= params.maxPrice!);
  }
  if (params.rating) {
    results = results.filter((h) => h.rating >= params.rating!);
  }

  return results;
}
