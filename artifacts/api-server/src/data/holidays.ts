export function searchHolidays(params: {
  destination?: string;
  theme?: string;
  duration?: number;
  maxPrice?: number;
}) {
  let results = [...holidaysData];

  if (params.destination) {
    const dest = params.destination.toLowerCase();
    results = results.filter(
      (p) =>
        p.destination.toLowerCase().includes(dest) ||
        p.country.toLowerCase().includes(dest) ||
        p.title.toLowerCase().includes(dest)
    );
  }
  if (params.theme) {
    const themeMap: Record<string, string[]> = {
      "Romantic": ["Romantic"],
      "Adventure": ["Adventure"],
      "Beach": ["Beach"],
      "Cultural": ["Cultural", "Heritage", "City Break"],
      "Family": ["Family"],
    };
    const allowed = themeMap[params.theme] || [params.theme];
    results = results.filter((p) =>
      allowed.some((t) => p.theme.toLowerCase().includes(t.toLowerCase()))
    );
  }
  if (params.duration) {
    results = results.filter((p) => p.duration <= params.duration!);
  }
  if (params.maxPrice) {
    results = results.filter((p) => p.price <= params.maxPrice!);
  }

  return results;
}
