export function searchHolidays(params: {
  destination?: string;
  theme?: string;
  duration?: number;
  maxPrice?: number;
}) {
  let results = [...holidaysData];

  if (params.destination) {
    const dest = params.destination.toLowerCase();
    results = results.filter(
      (p) =>
        p.destination.toLowerCase().includes(dest) ||
        p.country.toLowerCase().includes(dest)
    );
  }
  if (params.theme) {
    results = results.filter((p) =>
      p.theme.toLowerCase().includes(params.theme!.toLowerCase())
    );
  }
  if (params.duration) {
    results = results.filter((p) => p.duration <= params.duration!);
  }
  if (params.maxPrice) {
    results = results.filter((p) => p.price <= params.maxPrice!);
  }

  return results;
}
