// GET /trains/live-status/:trainNumber
router.get("/trains/live-status/:trainNumber", async (req, res): Promise<void> => {
  const { trainNumber } = req.params;
  try {
    const [train] = await db
      .select()
      .from(trainsTable)
      .where(eq(trainsTable.trainNumber, trainNumber.trim()))
      .limit(1);

    if (!train) {
      res.status(404).json({ error: "Train not found", message: `Train ${trainNumber} is not in our database.` });
      return;
    }

    const liveData = computeLiveStatus(train.trainNumber, train.fromStation, train.toStation, train.routeKey);
    liveData.trainName = train.trainName;
    liveData.trainType = train.trainType;

    res.json({ success: true, data: liveData });
  } catch (err) {
    res.status(500).json({ error: "Server error" });
  }
});

// GET /trains/search?q=...
router.get("/trains/search", async (req, res): Promise<void> => {
  const q = (req.query.q as string ?? "").trim();
  if (!q || q.length < 2) {
    res.json({ success: true, data: [] });
    return;
  }
  try {
    const results = await db
      .select()
      .from(trainsTable)
      .where(
        or(
          ilike(trainsTable.trainNumber, `%${q}%`),
          ilike(trainsTable.trainName, `%${q}%`),
          ilike(trainsTable.fromStation, `%${q}%`),
          ilike(trainsTable.toStation, `%${q}%`),
        ),
      )
      .limit(20);
    res.json({ success: true, data: results });
  } catch (err) {
    res.status(500).json({ error: "Server error" });
  }
});

