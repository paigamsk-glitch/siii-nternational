// ─── Live status computation ──────────────────────────────────────────────────
function computeLiveStatus(trainNumber: string, fromStation: string, toStation: string, routeKey: string) {
  const now = new Date();
  const seed = trainNumber.split("").reduce((a, c) => a + c.charCodeAt(0), 0);
  const totalMinsInDay = now.getHours() * 60 + now.getMinutes();
  const offset = seed % 240; // 0-240 minute offset per train
  const trainMins = (totalMinsInDay + offset) % 1440;

  // Map train position to percentage 0-100
  const percent = Math.round((trainMins / 1440) * 100);

  const stops = getRouteStops(routeKey);
  const allStops = [fromStation, ...stops, toStation];
  const stopIndex = Math.floor((percent / 100) * (allStops.length - 1));
  const currentIdx = Math.min(stopIndex, allStops.length - 1);

  const currentStation = allStops[currentIdx];
  const nextStation = currentIdx < allStops.length - 1 ? allStops[currentIdx + 1] : toStation;

  // Delay based on train seed
  const delaySeed = seed % 5;
  const delayMins = delaySeed === 0 ? 0 : delaySeed === 1 ? 5 : delaySeed === 2 ? 10 : delaySeed === 3 ? 0 : 15;

  // Stop statuses
  const stopsData = allStops.map((name, i) => {
    let status: "departed" | "current" | "upcoming";
    if (i < currentIdx) status = "departed";
    else if (i === currentIdx) status = "current";
    else status = "upcoming";

    const baseHour = 6 + Math.floor((i / allStops.length) * 18);
    const baseMins = (i * 47) % 60;
    const schedTime = `${String(baseHour).padStart(2, "0")}:${String(baseMins).padStart(2, "0")}`;

    return {
      code: name.toUpperCase().replace(/[^A-Z]/g, "").slice(0, 5) || "STA",
      name,
      scheduledArrival: i === 0 ? null : schedTime,
      scheduledDeparture: i === allStops.length - 1 ? null : schedTime,
      actualArrival: (status === "departed" || status === "current") && i > 0
        ? `${String(baseHour).padStart(2, "0")}:${String(Math.min(59, baseMins + delayMins)).padStart(2, "0")}`
        : null,
      actualDeparture: status === "departed" && i < allStops.length - 1
        ? `${String(baseHour).padStart(2, "0")}:${String(Math.min(59, baseMins + delayMins)).padStart(2, "0")}`
        : null,
      platform: `${(seed + i) % 8 + 1}`,
      haltMins: i === 0 || i === allStops.length - 1 ? 0 : (i * 3) % 10 + 1,
      distance: Math.round((i / allStops.length) * 1500),
      day: i < allStops.length / 2 ? 1 : 2,
      delayMins: status === "departed" ? delayMins : status === "current" ? delayMins : 0,
      status,
    };
  });

  const trainType = trainNumber.startsWith("120") ? "Shatabdi"
    : trainNumber.startsWith("12") && parseInt(trainNumber) < 12300 ? "Jan Shatabdi"
    : parseInt(trainNumber) >= 12301 && parseInt(trainNumber) <= 12453 ? "Rajdhani"
    : parseInt(trainNumber) >= 12213 && parseInt(trainNumber) <= 12299 ? "Duronto"
    : "Express";

  return {
    trainNumber,
    trainName: null, // filled by caller
    trainType,
    from: fromStation,
    to: toStation,
    fromCode: fromStation.toUpperCase().replace(/[^A-Z]/g, "").slice(0, 5),
    toCode: toStation.toUpperCase().replace(/[^A-Z]/g, "").slice(0, 5),
    currentStation,
    nextStation,
    currentBetween: currentIdx < allStops.length - 1 ? [currentStation, nextStation] : null,
    percentComplete: percent,
    delayMins,
    lastUpdated: `${now.getHours()}:${String(now.getMinutes()).padStart(2, "0")}`,
    stops: stopsData,
  };
}

